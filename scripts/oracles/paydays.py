# Independent oracle for payday tables: Python datetime + the GOV.UK feed.
# Regenerate: python3 -I scripts/oracles/paydays.py src/domain/data/bank-holidays.json > src/domain/__fixtures__/payday-tables.ts
import json, sys, calendar
from datetime import date, timedelta
feed = json.load(open(sys.argv[1]))
hol = {r: {e['date'] for e in v['events']} for r, v in feed.items()}
FROM, TO = date(2026,1,1), date(2028,12,31)

def working(d, r): return d.weekday() < 5 and d.isoformat() not in hol[r]
def back(d, r):
    while not working(d, r): d -= timedelta(days=1)
    return d

def monthly(day):
    out = []
    for y in range(2025, 2030):
        for m in range(1, 13):
            last = calendar.monthrange(y, m)[1]
            out.append(date(y, m, last if day == 'last' else min(day, last)))
    return out

def weekly(anchor, n):
    a = date.fromisoformat(anchor); out = []
    d = a
    while d > date(2025,11,1): d -= timedelta(weeks=n)
    while d < date(2029,2,1): out.append(d); d += timedelta(weeks=n)
    return out

def table(nominals, r):
    rows = []
    for nom in nominals:
        act = back(nom, r)
        if FROM <= act <= TO: rows.append((nom.isoformat(), act.isoformat()))
    return rows

cases = {
  'monthly25EW': (monthly(25), 'england-and-wales'),
  'monthly1EW': (monthly(1), 'england-and-wales'),
  'monthly31EW': (monthly(31), 'england-and-wales'),
  'monthly13NI': (monthly(13), 'northern-ireland'),
  'lastWorkingDayEW': (monthly('last'), 'england-and-wales'),
  'lastWorkingDaySC': (monthly('last'), 'scotland'),
  'lastWorkingDayNI': (monthly('last'), 'northern-ireland'),
  'fourWeeklyEW': (weekly('2026-01-09', 4), 'england-and-wales'),
  'fortnightlyEW': (weekly('2026-01-02', 2), 'england-and-wales'),
  'weeklyEW': (weekly('2026-01-05', 1), 'england-and-wales'),
}
print('// Generated by scripts/oracles/paydays.py, an independent Python oracle (datetime + GOV.UK bank-holidays.json).')
print('// Each row is [nominal payday, actual payday after moving back to a working day].')
print('// Do not regenerate these from the TypeScript under test.')
print("export const PAYDAY_TABLES: Record<string, readonly (readonly [string, string])[]> = {")
for name, (noms, r) in cases.items():
    rows = table(noms, r)
    shifted = sum(1 for a, b in rows if a != b)
    print(f'  // {r}: {len(rows)} paydays, {shifted} moved')
    print(f'  {name}: [')
    for a, b in rows: print(f"    ['{a}', '{b}'],")
    print('  ],')
print('};')
